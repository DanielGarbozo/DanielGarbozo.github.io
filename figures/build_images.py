#!/usr/bin/env python
"""Build every web image in assets/img/ from its source, reproducibly.

For each slot: fetch the source if it is remote (third-party images come from their
Wikimedia Commons file pages, see CREDITS.md), crop to the slot's aspect ratio, resize,
and write a WebP plus a JPEG or PNG fallback. Fails loudly if any output exceeds the
size budget.

Sources
    figures/*.png                       generated by figures/make_*.py (this repo)
    git_profile_pic.jpg                 my photo, kept at the repository root
    Omicskit_fig1_architecture.png      OmicsKit architecture diagram (no results)
    peroPOA_snRNAseq figures            my public repository
    Wikimedia Commons                   third-party, license recorded in CREDITS.md

Downloads are cached in data/img-src/ (gitignored).
Usage:  python figures/build_images.py
Requires: pillow (with WebP support).
"""
from __future__ import annotations

import pathlib
import time
import urllib.request

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
CACHE = ROOT / "data" / "img-src"
OUT = ROOT / "assets" / "img"
BUDGET_KB = 300
UA = {"User-Agent": "static-site-image-build/1.0"}

COMMONS = "https://thumb.wikimedia.org/wikipedia/commons/thumb/"
REMOTE = {
    "celegans.jpg": COMMONS + "5/51/C._elegans%2C_model_organism_in_life_sciences_%2828703152561%29.jpg/"
                    "1280px-C._elegans%2C_model_organism_in_life_sciences_%2828703152561%29.jpg",
    "tcruzi.png": COMMONS + "a/ad/Trypanosoma_cruzi_%28NIH_BioArt_634%29.png/"
                  "1280px-Trypanosoma_cruzi_%28NIH_BioArt_634%29.png",
    "mtb.jpg": COMMONS + "c/cb/Mycobacterium_tuberculosis.jpg/1280px-Mycobacterium_tuberculosis.jpg",
    "idc.jpg": COMMONS + "e/eb/Histopathology_of_invasive_ductal_carcinoma%2C_intermediate_magnification.jpg/"
               "1280px-Histopathology_of_invasive_ductal_carcinoma%2C_intermediate_magnification.jpg",
    "hen.jpg": COMMONS + "f/f1/Free_Range_Chicken.jpg/1280px-Free_Range_Chicken.jpg",
    "flowcell.jpg": "https://upload.wikimedia.org/wikipedia/commons/4/4c/DNA_Nanoball_sequencing_flow_cell.jpg",
    "perpoa_umap.png": "https://raw.githubusercontent.com/DanielGarbozo/peroPOA_snRNAseq/main/figures/"
                       "umap_moffitt_labels.png",
}


def source(name: str) -> pathlib.Path:
    """Local path for a source; download remote ones into the cache once."""
    local = ROOT / name
    if local.exists():
        return local
    cached = CACHE / name
    if not cached.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        for attempt in range(5):
            try:
                req = urllib.request.Request(REMOTE[name], headers=UA)
                with urllib.request.urlopen(req, timeout=120) as r:
                    cached.write_bytes(r.read())
                break
            except Exception as ex:  # Commons rate-limits bursts (HTTP 429)
                print(f"  retry {attempt + 1} for {name}: {ex}")
                time.sleep(10 * (attempt + 1))
        else:
            raise SystemExit(f"could not download {name}")
    return cached


def crop_aspect(im: Image.Image, aspect: float, focus=(0.5, 0.5), box=None) -> Image.Image:
    """Largest crop with width/height == aspect, centered on `focus` (fractions)."""
    if box:
        im = im.crop(box)
    w, h = im.size
    if w / h > aspect:
        cw, ch = round(h * aspect), h
    else:
        cw, ch = w, round(w / aspect)
    cx = min(max(focus[0] * w, cw / 2), w - cw / 2)
    cy = min(max(focus[1] * h, ch / 2), h - ch / 2)
    return im.crop((round(cx - cw / 2), round(cy - ch / 2), round(cx + cw / 2), round(cy + ch / 2)))


def fit_pad(im: Image.Image, aspect: float, fill, box=None) -> Image.Image:
    """Letterbox the whole image onto a canvas of the given aspect."""
    if box:
        im = im.crop(box)
    w, h = im.size
    cw, ch = (round(h * aspect), h) if w / h < aspect else (w, round(w / aspect))
    canvas = Image.new("RGB", (cw, ch), fill)
    canvas.paste(im, ((cw - w) // 2, (ch - h) // 2))
    return canvas


# name -> (source file, transform, output width, fallback format)
CARD = 16 / 10
SLOTS = {
    "hero-hic": ("figures/hic_chrX_hero.png", lambda im: im, None, "jpg"),
    "profile": ("git_profile_pic.jpg", lambda im: crop_aspect(im, 1.0), 400, "jpg"),
    "research-celegans": ("celegans.jpg", lambda im: crop_aspect(im, CARD, (0.42, 0.40)), 800, "jpg"),
    "research-fountain": ("figures/fountain_toy.png", lambda im: crop_aspect(im, CARD), 800, "jpg"),
    "research-atac": ("figures/atac_schematic.png", lambda im: crop_aspect(im, CARD), 800, "jpg"),
    "research-tcruzi": ("tcruzi.png", lambda im: fit_pad(im, CARD, (0, 0, 0), box=(80, 60, 1220, 1220)), 800, "jpg"),
    "research-mtb": ("mtb.jpg", lambda im: crop_aspect(im, CARD, (0.5, 0.42)), 800, "jpg"),
    "research-perpoa": ("perpoa_umap.png",
                        lambda im: crop_aspect(im, CARD, (0.5, 0.47), box=(56, 86, 1321, 1143)), 800, "jpg"),
    "research-poultry": ("hen.jpg", lambda im: crop_aspect(im, CARD, (0.55, 0.45)), 800, "jpg"),
    "research-histology": ("idc.jpg", lambda im: crop_aspect(im, CARD), 800, "jpg"),
    "strip-flowcell": ("flowcell.jpg", lambda im: im.crop((12, 10, 1252, 470)), None, "jpg"),
    "omicskit-architecture": ("Omicskit_fig1_architecture.png", lambda im: im, None, "png"),
}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    over = []
    print(f"{'slot':24s} {'size':>11s} {'webp':>8s} {'fallback':>9s}")
    for slot, (src, transform, width, fallback) in SLOTS.items():
        im = transform(Image.open(source(src)).convert("RGB"))
        if width and im.width != width:
            im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
        webp = OUT / f"{slot}.webp"
        im.save(webp, "WEBP", quality=80, method=6)
        fb = OUT / f"{slot}.{fallback}"
        if fallback == "png":
            im.quantize(colors=128, method=Image.Quantize.MEDIANCUT).save(fb, optimize=True)
        else:
            im.save(fb, "JPEG", quality=80, optimize=True, progressive=True)
        kb_w, kb_f = webp.stat().st_size / 1024, fb.stat().st_size / 1024
        print(f"{slot:24s} {im.width:5d}x{im.height:<5d} {kb_w:7.0f}K {kb_f:8.0f}K")
        over += [p.name for p, kb in ((webp, kb_w), (fb, kb_f)) if kb > BUDGET_KB]
    if over:
        raise SystemExit(f"over the {BUDGET_KB} KB budget: {over}")


if __name__ == "__main__":
    main()
